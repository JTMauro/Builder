def _polite() -> None:
    """At most one archive.org request a second."""
    wait = _last_net[0] + 1.0 - time.time()
    if wait > 0:
        time.sleep(wait)
    _last_net[0] = time.time()


def _cached_json(key: str, url: str, ttl_s: float = 7 * 86400) -> Any:
    from . import assets

    f = _cache_dir() / f"{hashlib.sha1(key.encode()).hexdigest()[:20]}.json"
    if f.exists() and time.time() - f.stat().st_mtime < ttl_s:
        try:
            return json.loads(f.read_text(encoding="utf-8"))
        except ValueError:
            pass
    _polite()
    data = assets._get_json(url)
    f.write_text(json.dumps(data), encoding="utf-8")
    return data


def _preview(identifier: str, fmeta: dict[str, Any], seconds: float = 30.0) -> Path:
    """The first `seconds` of music from about a quarter into the track (one ranged request, cached)."""
    from . import assets

    name = fmeta["name"]
    f = _cache_dir() / f"pv_{hashlib.sha1(f'{identifier}/{name}'.encode()).hexdigest()[:20]}{Path(name).suffix.lower() or '.mp3'}"
    if f.exists() and f.stat().st_size > 10_000:
        return f
    size = int(float(fmeta.get("size") or 0))
    length = _length_s(fmeta.get("length")) or 0
    rate = size / length if size and length else 24_000
    a = int(size * 0.25) if size and length > seconds * 2 else 0
    b = a + int(rate * seconds)
    url = f"https://archive.org/download/{urllib.parse.quote(identifier)}/{urllib.parse.quote(name)}"
    assets._check_public(url)
    _polite()
    req = urllib.request.Request(url, headers={"User-Agent": assets.UA, "Range": f"bytes={a}-{b}"})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            data = r.read(b - a + 1)
    except (urllib.error.URLError, TimeoutError) as e:
        raise OpError(f"Couldn't fetch a preview of {identifier}: {getattr(e, 'reason', e)}") from e
    f.write_bytes(data)
    return f


def _length_s(v: Any) -> float | None:
    if v is None:
        return None
    s = str(v)
    try:
        if ":" in s:
            parts = [float(x) for x in s.split(":")]
            return sum(x * 60 ** i for i, x in enumerate(reversed(parts)))
        return float(s)
    except ValueError:
        return None


def parse_music_words(words: str) -> dict[str, Any]:
    """Mood, tempo and instrument words to search terms and measurable targets."""
    toks = [t for t in re.findall(r"[a-z]+|\d+", words.lower())]
    moods, instruments, other = [], [], []
    target: dict[str, Any] = {}
    for i, t in enumerate(toks):
        m = FM_ALIASES.get(t, t)
        if m in FM_MOODS:
            moods.append(m)
        elif t in FM_TEMPO:
            target["bpm"] = FM_TEMPO[t]
        elif t.isdigit() and i + 1 < len(toks) and toks[i + 1] == "bpm":
            target["bpm"] = (int(t) * 0.9, int(t) * 1.1)
        elif t in FM_INSTRUMENTS or t.rstrip("s") in FM_INSTRUMENTS:
            instruments.append(t.rstrip("s") if t.rstrip("s") in FM_INSTRUMENTS else t)
        elif t not in FM_STOP and t != "bpm" and not t.isdigit() and len(t) > 2:
            other.append(t)
    for m in moods:
        for k, v in FM_MOODS[m].items():
            if k != "terms":
                target.setdefault(k, v)
    terms = [t for m in moods for t in FM_MOODS[m]["terms"]]
    return {"moods": moods, "instruments": instruments, "other": other, "target": target, "terms": list(dict.fromkeys(terms))}


def _search(parsed: dict[str, Any], rows: int) -> list[dict[str, Any]]:
    base = f"(collection:musopen* OR (licenseurl:*publicdomain* AND year:[1800 TO {PD_RECORDING_YEAR}])) AND mediatype:audio"
    q_inst = " OR ".join(parsed["instruments"])
    q_other = " AND ".join(parsed["other"])
    q_mood = " OR ".join(parsed["terms"])
    tries = []
    for parts in ([q_inst, q_other, q_mood], [q_inst, q_other], [q_inst or q_other or q_mood]):
        q = " AND ".join(f"({x})" for x in parts if x)
        if q and q not in tries:
            tries.append(q)
    if not tries:
        tries = ["classical"]
    for q in tries:
        url = "https://archive.org/advancedsearch.php?" + urllib.parse.urlencode(
            {"q": f"{q} AND {base}", "fl[]": ["identifier", "title", "creator", "licenseurl", "collection", "downloads", "year"],
             "sort[]": "downloads desc", "rows": rows, "output": "json"}, doseq=True)
        docs = _cached_json("search:" + url, url).get("response", {}).get("docs", [])
        if docs:
            return docs
    return []


def _pick_track(meta: dict[str, Any], parsed: dict[str, Any]) -> dict[str, Any] | None:
    files = [f for f in meta.get("files", []) if str(f.get("name", "")).lower().endswith((".mp3", ".ogg"))]
    if not files:
        return None
    # prefer small derivative MP3s, tracks of a usable length, names that match the request
    words = parsed["instruments"] + parsed["other"] + parsed["terms"]

    part = re.compile(r"\b(section|part|parts|stem|stems|minus|only|click|practice|solo [a-z]+$)\b|\b(1st|2nd|3rd|4th)\b")
    names = {str(f["name"]) for f in files}

    def score(f: dict[str, Any]) -> tuple:
        ln = _length_s(f.get("length")) or 120
        name = str(f["name"])
        hay = f"{name} {f.get('title', '')}".lower()
        # a full performance, not an instrument part or a practice stem; the original upload over its derivative copies
        is_part = bool(part.search(Path(hay).stem if "/" not in hay else hay))
        has_mp3_twin = name.lower().endswith((".flac", ".ogg")) and Path(name).with_suffix(".mp3").name in names
        return (is_part, f.get("source") != "original" and len(files) > 3, -sum(w in hay for w in words), not (20 <= ln <= 900),
                not name.lower().endswith(".mp3") or has_mp3_twin, "64kb" not in name.lower(), name)

    return sorted(files, key=score)[0]


def _features(path: Path) -> dict[str, Any]:
    """Tempo, brightness, energy and key/mode of a music preview (signal heuristics)."""
    from . import review

    np = _np()
    st = review._decode(path, 40, 1)
    mono = st[:, 0].astype(np.float32) if len(st) else np.zeros(0, np.float32)
    if len(mono) < review.SR_A * 5:
        raise OpError("preview too short")
    sp = review._spectral(np, mono)
    fps = review.SR_A / review.HOP
    tempo = review._tempo(np, sp["flux"], fps)
    frame_db = 10 * np.log10(sp["power"] + 1e-20)
    loud = frame_db > float(frame_db.max()) - 40
    w = sp["power"] * loud
    centroid = float((sp["centroid"] * w).sum() / (w.sum() or 1))
    # onsets from a band-smoothed flux (60 Hz-4 kHz in 32 bands) so record crackle and hiss don't count as notes
    n, h = 2048, 512
    x = mono.astype(np.float64)
    nfr = 1 + (len(x) - n) // h
    mags = np.abs(np.fft.rfft(x[np.arange(n)[None, :] + h * np.arange(nfr)[:, None]] * np.hanning(n), axis=1))
    sel = (sp["freqs"] > 60) & (sp["freqs"] < 4000)
    M = np.log1p(30 * mags[:, sel] / (mags[:, sel].mean() + 1e-9))
    B = np.add.reduceat(M, np.linspace(0, M.shape[1], 33).astype(int)[:-1], axis=1)
    fl = np.maximum(0, np.diff(B, axis=0)).sum(axis=1)
    thr = np.median(fl) + 3 * np.median(np.abs(fl - np.median(fl)))
    peaks = (fl[1:-1] > thr) & (fl[1:-1] >= fl[:-2]) & (fl[1:-1] > fl[2:])
    onset_rate = float(peaks.sum()) / (len(mono) / review.SR_A)
    contrast = float(np.percentile(fl, 95) / (np.median(fl) + 1e-9))   # how sharp the attacks are
    rms_db = 20 * math.log10(float(np.sqrt(np.mean(x ** 2))) + 1e-9)

    def c01(v: float) -> float:
        return min(1.0, max(0.0, v))

    energy = (0.35 * c01((contrast - 1.5) / 3) + 0.25 * c01(tempo["regularity"] / 0.6) + 0.2 * c01(onset_rate / 4.5)
              + 0.2 * c01((rms_db + 32) / 18))
    freqs, spec = sp["freqs"], sp["mean_spec"]
    sel = (freqs > 60) & (freqs < 2000)
    pcs = (np.round(12 * np.log2(freqs[sel] / 440.0)).astype(int) + 9) % 12
    chroma = np.bincount(pcs, weights=spec[sel], minlength=12)
    chroma = chroma / (chroma.sum() or 1)
    best = []
    for mode, prof in (("major", _KK_MAJOR), ("minor", _KK_MINOR)):
        for k in range(12):
            best.append((float(np.corrcoef(chroma, np.roll(prof, k))[0, 1]), mode, k))
    best.sort(reverse=True)
    r, mode, k = best[0]
    other = next(b for b in best if b[1] != mode)
    return {"bpm": tempo["bpm"], "beat_regularity": tempo["regularity"], "centroid_hz": round(centroid),
            "brightness": "dark/warm" if centroid < 900 else "balanced" if centroid < 2500 else "bright",
            "energy": round(energy, 2), "onsets_per_s": round(onset_rate, 2), "attack_contrast": round(contrast, 2), "key": f"{_PCS[k]} {mode}",
            "mode": mode, "mode_confidence": round(max(0.0, r - other[0]), 3)}


def score_music(feat: dict[str, Any], target: dict[str, Any]) -> tuple[float, list[str]]:
    """0-100 match of measured features to the targets, with reasons."""
    pen, why = 0.0, []

    def rng_pen(v: float, lo: float, hi: float, scale: float) -> float:
        return 0.0 if lo <= v <= hi else min(1.0, (lo - v if v < lo else v - hi) / scale)

    if "bpm" in target and feat.get("bpm"):
        lo, hi = target["bpm"]
        p = min(rng_pen(feat["bpm"], lo, hi, 40), rng_pen(feat["bpm"] * 2, lo, hi, 40) + 0.2, rng_pen(feat["bpm"] / 2, lo, hi, 40) + 0.2)
        pen += 1.0 * p
        why.append(f"tempo ~{feat['bpm']:.0f} BPM {'fits' if p < 0.25 else 'off'} ({lo:.0f}-{hi:.0f})")
    if "bright" in target:
        lo, hi = target["bright"]
        c = feat["centroid_hz"]
        p = 0.0 if lo <= c <= hi else min(1.0, abs(math.log2(c / (lo if c < lo else hi))))
        pen += 0.8 * p
        why.append(f"{feat['brightness']} ({c} Hz) {'fits' if p < 0.25 else 'off'}")
    if "energy" in target:
        lo, hi = target["energy"]
        p = rng_pen(feat["energy"], lo, hi, 0.35)
        pen += 1.0 * p
        why.append(f"energy {feat['energy']} {'fits' if p < 0.25 else 'off'}")
    if "mode" in target:
        miss = feat["mode"] != target["mode"]
        pen += 0.6 * miss * min(1.0, 0.4 + feat["mode_confidence"] * 4)
        why.append(f"{feat['key']} ({'as wanted' if not miss else 'wanted ' + target['mode']})")
    return round(100 * math.exp(-pen), 1), why


class FindMusicParams(BaseModel):
    words: str = Field(min_length=2, max_length=200, description="Mood, tempo and instrument words, e.g. 'calm piano', 'triumphant march brass fast', 'sad cello slow', 'playful 120 bpm'")
    candidates: int = Field(6, ge=2, le=10, description="How many tracks to preview and measure (each costs two small archive.org requests, cached)")
    top: int = Field(3, ge=1, le=10, description="How many picks to return")
    use: str | None = Field(None, max_length=300, description="Import a pick: its rank from a previous find_music with the same words ('1'), or its id ('identifier/file.mp3')")
    length_s: float | None = Field(None, ge=3, le=600, description="With use: trim or loop the track to this length")
    start_s: float = Field(0, ge=0, le=3600, description="With use: where in the track to start")
    fade_in: float = Field(1.0, ge=0, le=10)
    fade_out: float = Field(2.5, ge=0, le=20)
    loudness: float = Field(-18, ge=-30, le=-10, description="With use: target loudness (-18 suits a bed under speech)")
    format: Literal["wav", "mp3"] = "mp3"


def _rank(p: FindMusicParams) -> tuple[list[dict[str, Any]], dict[str, Any], list[str]]:
    parsed = parse_music_words(p.words)
    docs = _search(parsed, max(p.candidates * 2, 8))
    picks, errors = [], []
    for d in docs:
        if len(picks) >= p.candidates:
            break
        ident = d["identifier"]
        try:
            meta = _cached_json("meta:" + ident, f"https://archive.org/metadata/{urllib.parse.quote(ident)}", ttl_s=30 * 86400)
            md = meta.get("metadata") or {}
            lic = str(md.get("licenseurl") or d.get("licenseurl") or "")
            cols = md.get("collection") or []
            cols = cols if isinstance(cols, list) else [cols]
            if not _trusted(md, lic, cols):
                continue
            track = _pick_track(meta, parsed)
            if not track:
                continue
            feat = _features(_preview(ident, track))
        except OpError as e:
            errors.append(f"{ident}: {e}")
            continue
        score, why = score_music(feat, parsed["target"])
        hay = f"{md.get('title', '')} {track.get('title', '')} {track['name']}".lower()
        hits = [w for w in parsed["instruments"] + parsed["other"] + parsed["terms"] if w in hay]
        score = round(min(100.0, score + 4 * len(hits)), 1)
        creator = md.get("creator") if isinstance(md.get("creator"), str) else ", ".join(md.get("creator") or []) or "unknown"
        title = track.get("title") or md.get("title") or track["name"]
        picks.append({"id": f"{ident}/{track['name']}", "title": title, "album": md.get("title"), "creator": creator,
                      "length_s": _length_s(track.get("length")), "page": f"https://archive.org/details/{ident}",
                      "license": "CC0 1.0" if "zero" in lic else "Public domain", "license_url": lic or "https://creativecommons.org/publicdomain/mark/1.0/",
                      "license_line": f"\"{title}\" ({creator}), {'CC0' if 'zero' in lic else 'public domain'}, via Internet Archive"
                                      + (" / Musopen" if any(str(c).startswith("musopen") for c in cols) else ""),
                      "measured": feat, "match": score, "why": why + ([f"title mentions {', '.join(hits[:3])}"] if hits else [])})
    picks.sort(key=lambda x: -x["match"])
    for i, pk in enumerate(picks, 1):
        pk["rank"] = i
    return picks, parsed, errors


def _crossfade_loop(np, x, n: int, xf: int):
    """Repeat x (frames x channels) to n frames with equal-power crossfades of xf frames."""
    if len(x) >= n:
        return x[:n]
    xf = min(xf, len(x) // 3)
    out = x.copy()
    fade = np.sin(np.linspace(0, math.pi / 2, xf))[:, None] ** 2
    while len(out) < n:
        tail = out[-xf:] * (1 - fade) + x[:xf] * fade
        out = np.concatenate([out[:-xf], tail, x[xf:]])
    return out[:n]


@operation("find_music", FindMusicParams, "Find public-domain music (Internet Archive incl. Musopen) by mood, tempo and instrument words: previews a few candidates, measures tempo, brightness, energy and major/minor, and ranks them by the requested mood, with licence lines. With use (a rank or id), imports that track trimmed or looped to length_s with fades and loudness, licence saved beside it.")
def find_music(p: FindMusicParams) -> OpResult:
    from . import assets
    from .sound_design import SR, _encode

    np = _np()
    if not p.use:
        picks, parsed, errors = _rank(p)
        if not picks:
            raise OpError("No public-domain music found for those words" + (f" ({'; '.join(errors[:3])})" if errors else "") +
                          ". Try fewer or simpler words (e.g. 'piano calm', 'march brass').")
        return OpResult(data={"picks": picks[: p.top], "understood": {k: parsed[k] for k in ("moods", "instruments", "other", "target")},
                              "previewed": len(picks), "errors": errors,
                              "next": "Import one with use='1' (its rank) or use='<id>', plus length_s.",
                              "note": "Scores come from signal measurements of a 30 s preview, not listening. Uploads marked public domain "
                                      "are usually old compositions and free recordings, but check the page."})
    ident = p.use.strip()
    pick = None
    if ident.isdigit():
        picks, _, _ = _rank(p)
        pick = next((x for x in picks if x["rank"] == int(ident)), None)
        if not pick:
            raise OpError(f"No pick number {ident} for these words")
        ident = pick["id"]
    if "/" not in ident:
        raise OpError("use should be a rank like '1' or an id like 'identifier/file.mp3' from find_music")
    item, fname = ident.split("/", 1)
    meta = _cached_json("meta:" + item, f"https://archive.org/metadata/{urllib.parse.quote(item)}", ttl_s=30 * 86400)
    md = meta.get("metadata") or {}
    lic = str(md.get("licenseurl") or "")
    cols = md.get("collection") or []
    cols = cols if isinstance(cols, list) else [cols]
    if not _trusted(md, lic, cols):
        raise OpError(f"That Internet Archive item isn't a Musopen recording or a public-domain recording from {PD_RECORDING_YEAR} or before")
    if not any(f.get("name") == fname for f in meta.get("files", [])):
        raise OpError(f"{item} has no file named {fname}")
    cached = _cache_dir() / f"full_{hashlib.sha1(ident.encode()).hexdigest()[:20]}{Path(fname).suffix.lower()}"
    if not cached.exists():
        _polite()
        assets._download(f"https://archive.org/download/{urllib.parse.quote(item)}/{urllib.parse.quote(fname)}", cached)
    x = _pcm(cached, SR, 2)
    x = x[int(p.start_s * SR):]
    w = SR // 20   # trim silent edges (applause gaps, run-out groove) so a loop doesn't fall silent
    k = len(x) // w
    if k > 4:
        lv = 10 * np.log10(np.mean(x[: k * w].astype(np.float64).reshape(k, w, -1) ** 2, axis=(1, 2)) + 1e-12)
        live = np.nonzero(lv > lv.max() - 40)[0]
        if len(live):
            x = x[live[0] * w: (live[-1] + 1) * w]
    track_n = len(x)
    if len(x) < SR:
        raise OpError("start_s is past the end of the track")
    n = int((p.length_s or len(x) / SR) * SR)
    x = _crossfade_loop(np, x, n, int(2.0 * SR)).astype(np.float32)
    L, R = x[:, 0].copy(), x[:, 1].copy()
    from .sound_design import _fades

    _fades(L, R, p.fade_in, p.fade_out)
    creator = md.get("creator") if isinstance(md.get("creator"), str) else ", ".join(md.get("creator") or []) or "unknown"
    title = (pick or {}).get("title") or md.get("title") or fname
    licence = {"source": "archive", "id": ident, "page": f"https://archive.org/details/{item}", "creator": creator,
               "license": "CC0 1.0" if "zero" in lic else "Public domain", "license_url": lic or "https://creativecommons.org/publicdomain/mark/1.0/",
               "attribution": f"\"{title}\" ({creator}), via Internet Archive, public domain (credit appreciated, not required)"}
    data = {"id": ident, "title": title, "duration_s": round(n / SR, 2), "looped": n > track_n, **licence}
    res = _guarded("find_music", [], f"{storage.safe_name(Path(fname).stem)[:50]}_{round(n / SR)}s.{p.format}",
                   lambda out: _encode(out, L, R, p.format, p.loudness, ["highpass=f=25"]), data=data)
    assets._save_license(res.outputs[0].id, licence)
    return res


# ================================================================ 8. make_sfx (procedural sound effects)
# Every generator returns stereo float arrays (L, R) at sound_design.SR. All original synthesis.


class _Fx:
    """Small toolkit around sound_design's DSP helpers."""

    def __init__(self, rng, intensity: float):
        from . import sound_design as sd

        self.sd, self.np, self.rng, self.k = sd, sd._np(), rng, intensity
        self.SR = sd.SR

    # -- basics
    def n(self, s: float) -> int:
        return max(1, int(round(s * self.SR)))

    def t(self, n: int):
        return self.np.arange(n) / self.SR

    def zeros(self, s: float):
        return self.np.zeros(self.n(s), self.np.float32), self.np.zeros(self.n(s), self.np.float32)

    def band(self, x, lo=None, hi=None, order=2, taps=1024, tilt=0.0):
        sd = self.sd
        return sd._filter(x.astype(self.np.float32), lambda f: sd._band(f, lo, hi, tilt, order), taps)

    def noise(self, s_or_n, lo=None, hi=None, order=2, taps=1024, tilt=0.0):
        n = s_or_n if isinstance(s_or_n, int) else self.n(s_or_n)
        return self.band(self.rng.standard_normal(n).astype(self.np.float32), lo, hi, order, taps, tilt)

    def decay(self, n: int, tau: float, attack: float = 0.0005):
        np = self.np
        t = self.t(n)
        a = np.clip(t / attack, 0, 1) if attack > 0 else 1.0
        return (a * np.exp(-t / tau)).astype(np.float32)

    def modes(self, n: int, partials, detune: float = 0.0):
        """Sum of decaying sines: partials = [(freq, tau, amp)]; detune Hz adds a beating twin to each."""
        np = self.np
        t = self.t(n)
        out = np.zeros(n, np.float32)
        for f, tau, a in partials:
            if f >= self.SR / 2 - 200:
                continue
            ph = self.rng.uniform(0, 2 * math.pi)
            s = np.sin(2 * math.pi * f * t + ph)
            if detune:
                d = self.rng.uniform(0.4, 1.0) * detune
                s = 0.6 * s + 0.4 * np.sin(2 * math.pi * (f + d) * t + ph * 1.7)
            out += (a * s * np.exp(-t / tau)).astype(np.float32)
        return out

    def saw(self, f_inst):
        """Band-limited sawtooth (PolyBLEP) following an instantaneous frequency array."""
        np = self.np
        dt = np.clip(f_inst / self.SR, 1e-6, 0.45)
        ph = (np.cumsum(dt) + self.rng.uniform(0, 1)) % 1.0
        y = 2 * ph - 1
        m = ph < dt
        u = ph[m] / dt[m]
        y[m] -= u + u - u * u - 1
        m = ph > 1 - dt
        u = (ph[m] - 1) / dt[m]
        y[m] -= u * u + u + u + 1
        return y.astype(np.float32)

    def tv_band(self, x, fc, bw_oct: float, nfft: int = 1024):
        """Time-varying band-pass: fc is a centre-frequency curve (same length as x), bw_oct its width in octaves."""
        np = self.np
        hop = nfft // 4
        pad = nfft
        xp = np.concatenate([np.zeros(pad, np.float32), x, np.zeros(pad + nfft, np.float32)])
        win = np.hanning(nfft + 1)[:-1]
        nfr = 1 + (len(xp) - nfft) // hop
        idx = np.arange(nfft)[None, :] + hop * np.arange(nfr)[:, None]
        X = np.fft.rfft(xp[idx] * win, axis=1)
        f = np.fft.rfftfreq(nfft, 1 / self.SR)
        centres = np.interp(np.arange(nfr) * hop + nfft // 2 - pad, np.arange(len(fc)), fc)
        dist = np.log2(np.maximum(f[None, :], 20) / np.maximum(centres[:, None], 20)) / (bw_oct / 2)
        X *= 1 / (1 + dist ** 4)
        frames = np.fft.irfft(X, nfft, axis=1) * win
        y = np.zeros(len(xp))
        for i in range(nfr):
            y[i * hop: i * hop + nfft] += frames[i]
        return (y[pad: pad + len(x)] / 1.5).astype(np.float32)

    def put(self, buf, at: float, sig, gain: float = 1.0):
        self.sd._put(buf, at, sig, gain)

    def put_st(self, L, R, at: float, sig, gain: float = 1.0, pan: float = 0.0):
        self.sd._put_st(L, R, at, sig, gain, pan)

    def reverb(self, L, R, seconds: float, wet: float, damp: float = 5000, predelay: float = 0.012):
        return self.sd._add_reverb(L, R, self.sd._reverb_ir(self.rng, seconds, damp, predelay), wet)

    def fit(self, x, n: int):
        """Pad with silence or cut to n samples."""
        return self.np.pad(x, (0, max(0, n - len(x))))[:n].astype(self.np.float32)

    def soft(self, x, drive: float = 1.5):
        np = self.np
        return (np.tanh(drive * x) / math.tanh(drive)).astype(np.float32)

    def norm(self, x, peak: float = 1.0):
        m = float(self.np.max(self.np.abs(x))) or 1.0
        return (x * (peak / m)).astype(self.np.float32)


# ---------------------------------------------------------------- crowd voices (formant-filtered glottal sources)

VOWELS = {  # (formant Hz, bandwidth Hz, amplitude), adult male; female formants are ~17% higher
    "a": [(730, 90, 1.0), (1090, 110, 0.5), (2440, 170, 0.18), (3400, 250, 0.06)],
    "e": [(530, 80, 1.0), (1840, 120, 0.45), (2480, 170, 0.2), (3500, 250, 0.06)],
    "o": [(570, 80, 1.0), (840, 90, 0.6), (2410, 170, 0.1)],
    "u": [(300, 60, 1.0), (870, 90, 0.3), (2240, 170, 0.05)],
    "i": [(270, 60, 1.0), (2290, 120, 0.3), (3010, 170, 0.15)],
    "h": [(900, 900, 0.5), (1800, 1400, 0.8), (3200, 2200, 0.6), (5200, 3000, 0.3)],   # breath / aspiration, no vowel
}


class _Crowd:
    """Accumulates many voices per (vowel, sex) group, then formant-filters each group once (filtering is linear)."""

    def __init__(self, fx: _Fx, n: int):
        self.fx, self.n = fx, n
        self.groups: dict[tuple[str, str], tuple[Any, Any]] = {}

    def add(self, start_s: float, f0, env, vowel: str, sex: str, breath: float = 0.12, pan: float = 0.0, voiced: float = 1.0) -> None:
        fx, np = self.fx, self.fx.np
        k = len(f0)
        src = voiced * fx.saw(f0) + breath * fx.rng.standard_normal(k).astype(np.float32)
        sig = (src * env).astype(np.float32)
        if (vowel, sex) not in self.groups:
            self.groups[(vowel, sex)] = (np.zeros(self.n, np.float32), np.zeros(self.n, np.float32))
        L, R = self.groups[(vowel, sex)]
        fx.put_st(L, R, start_s, sig, 1.0, pan)

    def render(self):
        fx, np, sd = self.fx, self.fx.np, self.fx.sd
        L, R = np.zeros(self.n, np.float32), np.zeros(self.n, np.float32)
        for (vowel, sex), (gl, gr) in self.groups.items():
            scale = 1.17 if sex == "f" else 1.0
            forms = [(fq * scale, bw * scale, a) for fq, bw, a in VOWELS[vowel]]

            def gain(f, forms=forms):
                g = 0.015 + sum(a / (1 + ((f - fq) / (bw / 2)) ** 2) for fq, bw, a in forms)
                return g / np.sqrt(1 + (f / 1500.0) ** 2) * sd._band(f, 90, 9000, order=2)

            L += sd._filter(gl, gain, 2048)
            R += sd._filter(gr, gain, 2048)
        return L, R


def _voice_f0(fx: _Fx, sex: str, lo_m: float, hi_m: float, lo_f: float, hi_f: float) -> float:
    return fx.rng.uniform(lo_m, hi_m) if sex == "m" else fx.rng.uniform(lo_f, hi_f)


def _jitter(fx: _Fx, k: int, rate: float = 6.0, depth: float = 0.012):
    return 1 + fx.sd._lfo(fx.rng, k, rate, -depth, depth)


def _applause(fx: _Fx, length: float, people: int, start_spread: float = 0.35, stop_from: float = 0.6):
    np, rng = fx.np, fx.rng
    n = fx.n(length)
    types = 8
    bufs = [(np.zeros(n, np.float32), np.zeros(n, np.float32)) for _ in range(types)]
    kernels = []
    for _ in range(types):
        fc = rng.uniform(700, 2000)
        kn = fx.n(0.045)
        k = fx.noise(kn, fc / 1.7, fc * 1.6, order=2, taps=256) * fx.decay(kn, rng.uniform(0.004, 0.009), 0.0003)
        k += 0.4 * fx.noise(kn, 250, 700, taps=256) * fx.decay(kn, 0.006, 0.0003)
        kernels.append(fx.norm(k))
    for _ in range(people):
        typ = int(rng.integers(types))
        pan = rng.uniform(-0.9, 0.9)
        rate = rng.uniform(3.4, 6.2)
        t = rng.uniform(0, start_spread)
        stop = length * rng.uniform(stop_from, 1.0) if stop_from < 1 else length
        amp = rng.uniform(0.4, 1.0)
        while t < stop:
            g = amp * math.exp(rng.normal(0, 0.25))
            ang = (pan + 1) * math.pi / 4
            i = int(t * fx.SR)
            bufs[typ][0][i] += g * math.cos(ang)
            bufs[typ][1][i] += g * math.sin(ang)
            t += (1 / rate) * rng.normal(1, 0.06)
    L, R = np.zeros(n, np.float32), np.zeros(n, np.float32)
    for (bl, br), k in zip(bufs, kernels):
        L += fx.sd._convolve(bl, k)[:n]
        R += fx.sd._convolve(br, k)[:n]
    return L, R


def _whistle(fx: _Fx, dur: float):
    np, rng = fx.np, fx.rng
    k = fx.n(dur)
    t = fx.t(k)
    f_a, f_b = rng.uniform(1700, 2300), rng.uniform(2500, 3100)
    f = f_a + (f_b - f_a) * np.clip(t / (dur * 0.35), 0, 1) - (f_b - f_a) * 0.5 * np.clip((t - dur * 0.6) / (dur * 0.4), 0, 1)
    f = f * (1 + 0.01 * np.sin(2 * math.pi * 6 * t))
    s = np.sin(2 * math.pi * np.cumsum(f) / fx.SR) + 0.05 * rng.standard_normal(k)
    env = np.clip(t / 0.04, 0, 1) * np.clip((dur - t) / 0.08, 0, 1)
    return (s * env).astype(np.float32)


def sfx_crowd_cheer(fx: _Fx, length: float):
    np, rng = fx.np, fx.rng
    n = fx.n(length)
    crowd = _Crowd(fx, n)
    voices = int(30 + 110 * fx.k)
    for _ in range(voices):
        sex = "m" if rng.random() < 0.55 else "f"
        f0 = _voice_f0(fx, sex, 140, 250, 240, 400) * (0.9 + 0.2 * fx.k)
        st = abs(rng.normal(0.08, 0.18))
        dur = min(length - st, rng.uniform(0.9, 2.6) * max(1.0, length / 3.5))
        if dur < 0.3:
            continue
        k = fx.n(dur)
        t = fx.t(k)
        rise = rng.uniform(0.15, 0.35) * dur
        contour = np.where(t < rise, 0.88 + 0.3 * t / rise, 1.18 - 0.22 * (t - rise) / max(1e-3, dur - rise))
        f = f0 * contour * _jitter(fx, k, 7, 0.02) * (1 + 0.025 * np.sin(2 * math.pi * rng.uniform(4.5, 7) * t))
        env = np.clip(t / rng.uniform(0.04, 0.15), 0, 1) * np.clip((dur - t) / rng.uniform(0.15, 0.5), 0, 1)
        env *= fx.sd._lfo(rng, k, 3, 0.7, 1.0)
        vowel = rng.choice(["e", "o", "a", "u"], p=[0.35, 0.3, 0.2, 0.15])
        pan = rng.uniform(-0.9, 0.9)
        crowd.add(st, f.astype(np.float32), env.astype(np.float32), vowel, sex, breath=0.25, pan=pan)
        crowd.add(st, f.astype(np.float32), (env * 0.25).astype(np.float32), "h", sex, breath=1.0, pan=pan, voiced=0.0)
    L, R = crowd.render()
    aL, aR = _applause(fx, length, int(25 + 70 * fx.k), stop_from=0.75)
    s = 0.5 * float(np.sqrt(np.mean(L ** 2))) / (float(np.sqrt(np.mean(aL ** 2))) or 1)
    L, R = L + aL * s, R + aR * s
    for _ in range(int(1 + 3 * fx.k)):
        w = _whistle(fx, rng.uniform(0.5, 0.9))
        fx.put_st(L, R, rng.uniform(0.1, max(0.2, length * 0.6)), w, 0.12 * float(np.max(np.abs(L))), rng.uniform(-0.7, 0.7))
    return fx.reverb(L, R, 2.2, 0.32, 4500, 0.03)


