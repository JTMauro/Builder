def sfx_crowd_laugh(fx: _Fx, length: float):
    np, rng = fx.np, fx.rng
    n = fx.n(length)
    crowd = _Crowd(fx, n)
    for _ in range(int(14 + 55 * fx.k)):
        sex = "m" if rng.random() < 0.5 else "f"
        f0 = _voice_f0(fx, sex, 120, 210, 220, 360)
        bursts = 1 + int(rng.random() < 0.4 * (length / 3))
        t0 = abs(rng.normal(0.05, 0.25))
        for _b in range(bursts):
            rate = rng.uniform(4.2, 6.0)
            syl = int(rng.integers(4, 10))
            dur = syl / rate + 0.25
            if t0 + dur > length:
                break
            k = fx.n(dur)
            t = fx.t(k)
            env = np.zeros(k, np.float32)
            aspir = np.zeros(k, np.float32)
            for s in range(syl):
                ts = s / rate * rng.normal(1, 0.04)
                u = t - ts
                on = u >= 0
                a = (0.6 + 0.4 * (1 - s / syl)) * rng.uniform(0.75, 1.0)
                env += np.where(on, a * np.clip(u / 0.015, 0, 1) * np.exp(-np.maximum(u, 0) / (0.4 / rate)), 0).astype(np.float32)
                aspir += np.where(on, a * np.exp(-np.maximum(u, 0) / 0.03), 0).astype(np.float32)
            f = f0 * (1.3 - 0.4 * t / dur) * (1 - 0.06 * ((t * rate) % 1.0)) * _jitter(fx, k, 8, 0.02)
            pan = rng.uniform(-0.9, 0.9)
            vowel = "a" if rng.random() < 0.7 else "e"
            crowd.add(t0, f.astype(np.float32), env, vowel, sex, breath=0.35, pan=pan)
            crowd.add(t0, f.astype(np.float32), aspir * 0.9 + env * 0.35, "h", sex, breath=1.0, pan=pan, voiced=0.0)
            t0 += dur + rng.uniform(0.1, 0.5)
    L, R = crowd.render()
    return fx.reverb(L, R, 1.8, 0.25, 4500, 0.025)


