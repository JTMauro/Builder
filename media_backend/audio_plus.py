def synth_sfx(kind: str, variant: str, length: float, seed: int, intensity: float):
    """(L, R) float arrays for one effect."""
    from .sound_design import _rng

    rng, _ = _rng(seed)
    fx = _Fx(rng, intensity)
    if kind == "crowd":
        L, R = {"cheer": sfx_crowd_cheer, "boo": sfx_crowd_boo, "laugh": sfx_crowd_laugh, "gasp": sfx_crowd_gasp,
                "applause": sfx_crowd_applause}[variant](fx, length)
    else:
        L, R = {"door": sfx_door, "car": sfx_car, "ui": sfx_ui, "weather": sfx_weather, "impact": sfx_impact,
                "swoosh": sfx_swoosh, "fanfare": sfx_fanfare, "gong": sfx_gong}[kind](fx, variant, length)
    np = fx.np
    n = fx.n(length)
    L, R = (fx.band(fx.fit(x, n), 25, None, order=2, taps=4096) for x in (L, R))   # rumble/DC cut before peak normalising
    fade = min(fx.n(0.05), n // 4)
    if fade:
        ramp = np.cos(np.linspace(0, math.pi / 2, fade)) ** 2
        L[-fade:] *= ramp
        R[-fade:] *= ramp
    return L, R


def _overshoot_db(L, R) -> float:
    """How far the true (4x oversampled) peak rises above the sample peak, in dB, plus a 0.3 dB margin."""
    np = _np()
    sp, tp = 1e-9, 1e-9
    for x in (L, R):
        n = len(x)
        X = np.fft.rfft(x.astype(np.float64))
        up = np.fft.irfft(X, 4 * n) * 4
        sp, tp = max(sp, float(np.max(np.abs(x)))), max(tp, float(np.max(np.abs(up))))
    return max(0.0, 20 * math.log10(tp / sp)) + 0.3


class SfxParams(BaseModel):
    kind: Literal["door", "crowd", "car", "ui", "weather", "impact", "swoosh", "fanfare", "gong"] = Field(
        description="; ".join(f"{k}: {', '.join(v)}" for k, v in SFX.items()) + " (footsteps: use the footsteps operation)")
    variant: str | None = Field(None, max_length=40, description="Which sound of the kind (default: the first listed)")
    length_s: float | None = Field(None, ge=0.1, le=60, description="Length; crowds, rain, wind, engine and creaks fill it, short hits get silence after")
    seed: int | None = Field(None, ge=0, le=2**31 - 1, description="Same seed = the same sound; leave empty for a new take")
    intensity: float = Field(0.7, ge=0, le=1, description="0 gentle .. 1 big: harder hits, bigger crowds, faster cars, heavier rain")
    format: Literal["wav", "mp3"] = "wav"


@operation("make_sfx", SfxParams, "Make an ORIGINAL sound effect (free, offline, seeded): door (open/close/slam/creak/knock), crowd (cheer/boo/applause/gasp/laugh), car (pass_by/horn/engine_idle), ui (click/pop/whoosh/success/error/notification), weather (thunder/wind_gust/rain_window), impact (punch/thud/clang/sword_clash/shield_hit), swoosh (light/heavy/sword), fanfare (short/long trumpet, fail trombone) and gong (big/small). Intensity 0-1; true peak about -1 dBTP at full intensity.")
def make_sfx(p: SfxParams) -> OpResult:
    from .sound_design import SR, _encode, _rng

    variants = SFX[p.kind]
    variant = (p.variant or next(iter(variants))).lower().replace(" ", "_").replace("-", "_")
    if variant not in variants:
        raise OpError(f"{p.kind} has these variants: {', '.join(variants)}")
    _, seed = _rng(p.seed)
    length = p.length_s or variants[variant]
    L, R = synth_sfx(p.kind, variant, length, seed, p.intensity)
    data = {"kind": p.kind, "variant": variant, "seed": seed, "intensity": p.intensity, "duration_s": round(len(L) / SR, 3), "license": LICENSE_NOTE}
    peak = -1.0 - 3.0 * (1 - p.intensity) ** 2   # true peak target
    peak -= _overshoot_db(L, R)                   # inter-sample peaks of short clicks rise above the sample peak
    return _guarded("make_sfx", [], f"sfx_{p.kind}_{variant}_{seed}.{p.format}",
                    lambda out: _encode(out, L, R, p.format, None, [], peak_db=peak), data=data)
