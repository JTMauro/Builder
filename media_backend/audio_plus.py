"""More audio, all free and on this computer: precise word timing, who spoke when, studio voice, public-domain
music finder and a procedural sound-effects library.

- Precise timing (`precise: true` on transcribe and lipsync): Whisper's word times refined by forced alignment
  with a wav2vec2 CTC model (facebook/wav2vec2-base-960h, Apache-2.0, ~380 MB, English), the same approach as
  WhisperX (BSD-2). WhisperX itself pins torch 2.8 and CUDA wheels, so the Viterbi alignment is done here in numpy.
- who_spoke: speaker diarisation with pyannote speaker-diarization-community-1 (CC-BY-4.0). The model is gated:
  it needs a free Hugging Face token (HF_TOKEN) and `pip install pyannote.audio`; without them it says how.
- enhance_voice: rough recordings to studio quality: DeepFilterNet 3 (MIT/Apache) noise and room removal, a
  bandwidth extension for phone-band audio (rebuilds the missing top and bottom octaves from the harmonics that
  are there), then EQ, de-essing, compression and loudness. (Resemble Enhance, MIT, needs deepspeed and a GPU-era
  torch pin: not practical on this CPU.)
- find_music: public-domain music on the Internet Archive (incl. Musopen) by mood, tempo and instrument words;
  short previews are measured (tempo, brightness, energy, major/minor) and ranked; `use` imports one trimmed or
  looped to a length with fades and its licence line.
- make_sfx: original sound effects synthesized with numpy: doors, crowds, cars, UI, weather, impacts, swooshes,
  a short trumpet fanfare and a gong. Seeded: the same seed gives the same sound.
"""

