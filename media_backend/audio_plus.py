def _np():
    try:
        import numpy as np
    except ImportError as e:
        raise OpError('This needs numpy: pip install "builder[voice]" (or pip install numpy)') from e
    return np


def _pcm(path: Path, sr: int, channels: int = 1):
    """Decode any audio/video file to float32 PCM [samples, channels] with ffmpeg."""
    np = _np()
    raw = subprocess.run([get_settings().ffmpeg, "-v", "error", "-i", str(path), "-map", "0:a:0", "-f", "f32le", "-ac", str(channels),
                          "-ar", str(sr), "-"], capture_output=True, check=False, **NO_WINDOW)
    if raw.returncode != 0 or not raw.stdout:
        raise OpError("Couldn't read audio from that file")
    x = np.frombuffer(raw.stdout[: len(raw.stdout) // (4 * channels) * 4 * channels], np.float32)
    return x.reshape(-1, channels)


def _write_wav(path: Path, x, sr: int) -> None:
    """Float mono or [n, ch] audio to a 16-bit wav (through ffmpeg so the header is right)."""
    np = _np()
    a = np.asarray(x, np.float32)
    ch = 1 if a.ndim == 1 else a.shape[1]
    with tempfile.TemporaryDirectory(prefix="ap-") as d:
        raw = Path(d) / "x.f32"
        a.tofile(raw)
        _ffmpeg("-f", "f32le", "-ar", str(sr), "-ac", str(ch), "-i", str(raw), "-c:a", "pcm_f32le", str(path))


