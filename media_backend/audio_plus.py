def _wood_thud(fx: _Fx, size: float = 1.0, hard: float = 1.0):
    np, rng = fx.np, fx.rng
    k = fx.n(0.5)
    v = rng.uniform(0.92, 1.08)
    body = fx.modes(k, [(95 * v / size, 0.07 * size, 1.0), (160 * v / size, 0.05, 0.7), (245 * v / size, 0.035, 0.5), (390 * v, 0.025, 0.3), (610 * v, 0.015, 0.18)])
    hit = fx.noise(k, 60, 1400 + 1800 * hard, taps=512) * fx.decay(k, 0.012 + 0.008 * hard, 0.0005)
    return fx.norm(body + 0.9 * hit)


def _metal_click(fx: _Fx, bright: float = 1.0):
    k = fx.n(0.08)
    v = fx.rng.uniform(0.9, 1.1)
    ring = fx.modes(k, [(2400 * v, 0.008, 1.0), (3650 * v, 0.006, 0.7), (5200 * v, 0.004, 0.4)])
    tick = fx.noise(k, 1800, 9000 * bright, taps=256) * fx.decay(k, 0.0012, 0.0001)
    return fx.norm(ring + 1.5 * tick)


def _creak(fx: _Fx, dur: float, lo: float = 25, hi: float = 110, squeak: float = 0.35):
    np, rng = fx.np, fx.rng
    n = fx.n(dur)
    rate = fx.sd._lfo(rng, n, 2.2, lo, hi)
    ph = np.cumsum(rate / fx.SR)
    idx = np.nonzero(np.diff(np.floor(ph)))[0]
    imp = np.zeros(n, np.float32)
    env = np.clip(fx.t(n) / 0.08, 0, 1) * np.clip((dur - fx.t(n)) / 0.12, 0, 1) * fx.sd._lfo(rng, n, 4, 0.4, 1.0)
    imp[idx] = (rng.uniform(0.4, 1.0, len(idx)) * env[idx]).astype(np.float32)
    kn = fx.n(0.06)
    v = rng.uniform(0.9, 1.1)
    body = fx.modes(kn, [(310 * v, 0.02, 1.0), (560 * v, 0.016, 0.8), (880 * v, 0.012, 0.6), (1350 * v, 0.008, 0.4), (2100 * v, 0.005, 0.2)])
    y = fx.sd._convolve(imp, body)[:n]
    if squeak:   # a hinge whine whose pitch follows the friction
        f = rate * rng.uniform(6, 9)
        tone = fx.saw(f) * env
        y = fx.norm(y) + squeak * fx.norm(fx.band(tone, 400, 3500, taps=512))
    return fx.norm(y)


def sfx_door(fx: _Fx, variant: str, length: float):
    np, rng = fx.np, fx.rng
    L, R = fx.zeros(length)
    k = fx.k
    if variant == "knock":
        t = 0.05
        for i in range(3):
            fx.put_st(L, R, t, _wood_thud(fx, 0.6, 1.2), 0.5 + 0.5 * k * (0.85 if i else 1), 0.0)
            t += rng.uniform(0.17, 0.24)
        return fx.reverb(L, R, 0.5, 0.12, 6000, 0.008)
    if variant == "creak":
        c = _creak(fx, min(length - 0.05, 0.8 + 1.2 * (0.5 + k / 2)))
        fx.put_st(L, R, 0.02, c, 0.8, 0.0)
        return fx.reverb(L, R, 0.6, 0.15, 6000, 0.008)
    if variant == "open":
        fx.put_st(L, R, 0.03, _metal_click(fx), 0.35, 0.1)
        fx.put_st(L, R, 0.11, _metal_click(fx, 0.7), 0.25, 0.1)
        c = _creak(fx, min(length - 0.4, rng.uniform(0.9, 1.3)), 20, 80, 0.25)
        fx.put_st(L, R, 0.25, c, 0.55, 0.0)
        air = fx.noise(1.2, 60, 500) * np.sin(np.linspace(0, math.pi, fx.n(1.2))) ** 2
        fx.put_st(L, R, 0.25, air.astype(np.float32), 0.06, 0.0)
        return fx.reverb(L, R, 0.6, 0.15, 6000, 0.008)
    if variant == "close":
        air = fx.noise(0.4, 60, 600) * np.sin(np.linspace(0, math.pi, fx.n(0.4))) ** 2
        fx.put_st(L, R, 0.02, air.astype(np.float32), 0.08, 0.0)
        fx.put_st(L, R, 0.38, _wood_thud(fx, 1.0, 0.6), 0.6 + 0.3 * k, 0.0)
        fx.put_st(L, R, 0.385, _metal_click(fx), 0.45, 0.1)
        fx.put_st(L, R, 0.44, _metal_click(fx, 0.8), 0.18, 0.1)
        return fx.reverb(L, R, 0.7, 0.18, 5500, 0.008)
    # slam
    air = fx.noise(0.25, 60, 900) * np.sin(np.linspace(0, math.pi, fx.n(0.25))) ** 2
    fx.put_st(L, R, 0.0, air.astype(np.float32), 0.12, 0.0)
    kn = fx.n(0.8)
    crack = fx.noise(kn, 300, 5000, taps=256) * fx.decay(kn, 0.02, 0.0003)
    boom = 0.6 * fx.modes(kn, [(55, 0.12, 1.0), (82, 0.09, 0.6)]) + fx.fit(_wood_thud(fx, 1.3, 1.4), kn) * 1.2 + 0.8 * crack
    fx.put_st(L, R, 0.2, fx.soft(fx.norm(boom), 1.6), 0.9, 0.0)
    for i in range(int(4 + 4 * k)):
        fx.put_st(L, R, 0.21 + rng.uniform(0, 0.16), _metal_click(fx, 0.6), rng.uniform(0.12, 0.3), rng.uniform(-0.3, 0.3))
    return fx.reverb(L, R, 1.1, 0.25, 5000, 0.01)


# ---------------------------------------------------------------- cars


def _engine(fx: _Fx, n: int, rpm, cylinders: int = 4, rough: float = 0.15):
    """Firing pulses through an exhaust resonance; rpm is an array (per sample)."""
    np, rng = fx.np, fx.rng
    fire = rpm / 60 * cylinders / 2
    ph = np.cumsum(fire / fx.SR)
    idx = np.nonzero(np.diff(np.floor(ph)))[0]
    imp = np.zeros(n, np.float32)
    cyl_gain = rng.uniform(1 - rough, 1 + rough, cylinders)
    imp[idx] = (cyl_gain[np.arange(len(idx)) % cylinders] * rng.normal(1, 0.08, len(idx))).astype(np.float32)
    kn = fx.n(0.05)
    pulse = fx.modes(kn, [(68, 0.03, 1.0), (135, 0.02, 0.6), (210, 0.012, 0.4), (380, 0.008, 0.25)]) + 0.5 * fx.noise(kn, 40, 900, taps=256) * fx.decay(kn, 0.008)
    body = fx.sd._convolve(imp, pulse)[:n]
    mech = fx.noise(n, 1200, 4500, taps=512) * (0.5 + 0.5 * np.cos(2 * math.pi * np.cumsum(fire / 2 / fx.SR)))
    return fx.norm(fx.band(body, 25, 2500, taps=1024) + 0.04 * mech.astype(np.float32))


def sfx_car(fx: _Fx, variant: str, length: float):
    np, rng = fx.np, fx.rng
    n = fx.n(length)
    if variant == "engine_idle":
        rpm = fx.sd._lfo(rng, n, 1.5, 720, 800)
        e = _engine(fx, n, rpm, 4, 0.12 + 0.1 * fx.k)
        L, R = e.copy(), e.copy()
        return fx.reverb(L, R, 0.4, 0.06, 4000, 0.006)
    if variant in ("horn", "horn_double"):
        L, R = fx.zeros(length)
        beeps = [(0.02, min(0.55, length - 0.1))] if variant == "horn" else [(0.02, 0.18), (0.3, 0.32)]
        for st, d in beeps:
            k = fx.n(d + 0.05)
            t = fx.t(k)
            env = np.clip(t / 0.012, 0, 1) * np.clip((d - t) / 0.03, 0, 1)
            droop = 1 - 0.02 * np.exp(-t / 0.03)
            tone = fx.saw(np.full(k, 405.0) * droop) + 0.8 * fx.saw(np.full(k, 507.0) * droop)
            tone = fx.soft(tone * 0.6, 2.0)
            tone = fx.band(tone, 300, 4200, taps=1024)
            tone = tone + 0.6 * fx.band(tone, 1800, 3000, taps=512)
            fx.put_st(L, R, st, (tone * env).astype(np.float32), 1.0, 0.0)
        return fx.reverb(L, R, 0.9, 0.12, 4500, 0.02)
    # pass_by: engine + tyres + wind with Doppler, distance level and air absorption
    pre = fx.n(0.3)
    m = n + pre
    rpm = np.full(m, 2600.0 + 900 * fx.k) * fx.sd._lfo(rng, m, 0.7, 0.98, 1.02)
    eng = _engine(fx, m, rpm, 4, 0.1)
    tyre = fx.noise(m, 150, 2500, taps=1024, tilt=-1.0)
    wind = fx.noise(m, 40, 700, taps=1024)
    src = 0.55 * eng + 0.8 * fx.norm(tyre) * 0.5 + 0.25 * fx.norm(wind) * 0.5
    near = fx.norm(src)
    far = fx.band(near, None, 1200, taps=1024)
    v = 18 + 14 * fx.k
    d0 = 5.0
    t = fx.t(n)
    x = v * (t - length / 2)
    dist = np.sqrt(x ** 2 + d0 ** 2)
    delay = dist / 343.0
    idx = (t - delay) * fx.SR + pre
    a_near = np.interp(idx, np.arange(m), near)
    a_far = np.interp(idx, np.arange(m), far)
    closeness = d0 / dist
    sig = (a_near * closeness + a_far * (1 - closeness)) * closeness ** 0.9
    pan = np.clip(x / dist, -1, 1)
    ang = (pan + 1) * math.pi / 4
    L = (sig * np.cos(ang) * math.sqrt(2)).astype(np.float32)
    R = (sig * np.sin(ang) * math.sqrt(2)).astype(np.float32)
    return fx.reverb(L, R, 1.2, 0.08, 3500, 0.03)


