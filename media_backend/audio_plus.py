def sfx_weather(fx: _Fx, variant: str, length: float):
    np, rng = fx.np, fx.rng
    n = fx.n(length)
    if variant in ("thunder", "thunder_distant"):
        near = variant == "thunder"
        white = rng.standard_normal(n).astype(np.float32)
        brown = np.cumsum(white)
        brown -= np.convolve(brown, np.ones(4410) / 4410, mode="same")
        rumble = fx.band(brown.astype(np.float32), 25, 180 if not near else 260, order=3, taps=4096)
        t = fx.t(n)
        env = np.zeros(n)
        tt = 0.05 if near else 0.3
        for i in range(int(rng.integers(4, 8))):
            a = (0.85 ** i) * rng.uniform(0.6, 1.0)
            w = rng.uniform(0.3, 0.9)
            env += a * np.exp(-0.5 * ((t - tt) / w) ** 2)
            tt += rng.uniform(0.35, 1.1)
        env += 0.5 * np.exp(-t / (length / 2.5))
        env *= np.clip((length - t) / 0.6, 0, 1)
        mid = fx.noise(n, 200, 1600 if near else 700) * env * fx.sd._lfo(rng, n, 9, 0.3, 1.0)
        sig = fx.norm(rumble * env) + 0.3 * fx.norm(mid)
        L = (sig + 0.15 * fx.norm(fx.band(rng.standard_normal(n).astype(np.float32), 25, 200, taps=4096) * env)).astype(np.float32)
        R = (sig + 0.15 * fx.norm(fx.band(rng.standard_normal(n).astype(np.float32), 25, 200, taps=4096) * env)).astype(np.float32)
        if near:
            k = fx.n(0.5)
            crack = fx.noise(k, 300, 9000, tilt=-2.0) * fx.decay(k, 0.07, 0.002)
            crack = fx.soft(fx.norm(crack) * 1.4, 1.8)
            for j in range(6):
                fx.put_st(L, R, 0.03 + j * rng.uniform(0.01, 0.03), crack, 0.9 * 0.7 ** j, rng.uniform(-0.4, 0.4))
        return fx.reverb(L, R, 2.8, 0.4, 2500, 0.04)
    if variant == "wind_gust":
        t = fx.t(n)
        peak = length * rng.uniform(0.35, 0.5)
        g = np.where(t < peak, (t / peak) ** 1.5, np.exp(-(t - peak) / (length * 0.25)))
        g = g * fx.sd._lfo(rng, n, 3, 0.75, 1.0) * np.clip((length - t) / 0.3, 0, 1)
        out = []
        for _ in range(2):
            base = fx.noise(n, 30, 900, taps=2048, tilt=-2.0)
            fc = 300 + 900 * g
            howl = fx.tv_band(rng.standard_normal(n).astype(np.float32), fc, 0.5)
            out.append((fx.norm(base) * (0.35 + 0.65 * g) + 0.45 * fx.norm(howl) * g).astype(np.float32))
        return out[0], out[1]
    # rain_window: drops ticking on glass + soft rain beyond
    L, R = np.zeros(n, np.float32), np.zeros(n, np.float32)
    kernels = []
    for _ in range(6):
        kn = fx.n(0.03)
        f = rng.uniform(1800, 3800)
        kk = fx.noise(kn, 1200, 6000, taps=256) * fx.decay(kn, 0.0012, 0.0001) + 0.6 * fx.modes(kn, [(f, 0.004, 1.0), (f * 1.6, 0.0025, 0.4)])
        kernels.append(fx.norm(kk))
    big = []
    for _ in range(3):
        kn = fx.n(0.06)
        f = rng.uniform(1300, 2200)
        big.append(fx.norm(fx.noise(kn, 600, 5000, taps=256) * fx.decay(kn, 0.003) + fx.modes(kn, [(f, 0.012, 1.0), (f * 1.7, 0.006, 0.4)])))
    rate = 35 + 90 * fx.k
    for kern_set, r, amp in ((kernels, rate, 0.5), (big, 2 + 4 * fx.k, 0.9)):
        bl = [np.zeros(n, np.float32) for _ in kern_set]
        br = [np.zeros(n, np.float32) for _ in kern_set]
        m = rng.poisson(r * length)
        pos = rng.integers(0, n, m)
        for p_, j, a, pn in zip(pos, rng.integers(0, len(kern_set), m), rng.lognormal(0, 0.5, m) * amp, rng.uniform(-0.9, 0.9, m)):
            ang = (pn + 1) * math.pi / 4
            bl[j][p_] += a * math.cos(ang)
            br[j][p_] += a * math.sin(ang)
        for j, kk in enumerate(kern_set):
            L += fx.sd._convolve(bl[j], kk)[:n]
            R += fx.sd._convolve(br[j], kk)[:n]
    bed_l = fx.noise(n, 500, 5000, taps=1024, tilt=-1.5)
    bed_r = fx.noise(n, 500, 5000, taps=1024, tilt=-1.5)
    lvl = 0.25 * float(np.sqrt(np.mean(L ** 2))) / (float(np.sqrt(np.mean(bed_l ** 2))) or 1) * 2.5
    L, R = L + bed_l * lvl, R + bed_r * lvl
    return fx.reverb(L, R, 0.5, 0.12, 6000, 0.006)


