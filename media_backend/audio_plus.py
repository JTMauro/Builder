def deepfilter(x48, strength: float = 1.0):
    """DeepFilterNet 3 on 48 kHz mono float audio. strength 1 = full suppression, lower keeps some room sound."""
    import torch

    np = _np()
    model, state, enhance = _df_model()
    lim = None if strength >= 1 else 6 + 30 * strength
    with torch.inference_mode():
        y = enhance(model, state, torch.from_numpy(np.ascontiguousarray(x48, np.float32))[None], atten_lim_db=lim)
    return y[0].numpy().astype(np.float32)


def _ltas(np, x, sr: int):
    """Long-term average spectrum in dB (Welch, 4096-point), smoothed; returns (freqs, dB)."""
    n = 4096
    if len(x) < n:
        x = np.pad(x, (0, n - len(x)))
    hop = n // 2
    frames = 1 + (len(x) - n) // hop
    idx = np.arange(n)[None, :] + hop * np.arange(frames)[:, None]
    seg = x[idx] * np.hanning(n)
    rms = np.sqrt((seg ** 2).mean(axis=1))
    keep = rms > max(1e-6, np.percentile(rms, 60) * 0.3)   # speech frames, not pauses
    pw = (np.abs(np.fft.rfft(seg[keep] if keep.any() else seg, axis=1)) ** 2).mean(axis=0)
    db = 10 * np.log10(np.convolve(pw, np.ones(9) / 9, mode="same") + 1e-20)
    return np.fft.rfftfreq(n, 1 / sr), db


def measure_band(x, sr: int) -> dict[str, float]:
    """Where speech energy stops at the top and starts at the bottom (phone audio: ~300-3400 Hz)."""
    np = _np()
    f, db = _ltas(np, x, sr)
    ref = float(np.median(db[(f >= 300) & (f <= 3000)]))
    above = np.nonzero((db > ref - 50) & (f > 1000))[0]
    hi = float(f[above[-1]]) if len(above) else 1000.0
    low_band = float(np.mean(db[(f >= 90) & (f <= 220)]))
    mid_band = float(np.mean(db[(f >= 400) & (f <= 1200)]))
    lo = 300.0 if low_band < mid_band - 15 else 80.0
    return {"top_hz": round(hi), "bottom_hz": lo}


def _fir_band(np, x, sr, lo=None, hi=None, order=8, taps=2047):
    f = np.fft.rfftfreq(taps + 1, 1 / sr)
    g = np.ones_like(f)
    ff = np.maximum(f, 1.0)
    if lo:
        g /= np.sqrt(1 + (lo / ff) ** (2 * order))
    if hi:
        g /= np.sqrt(1 + (ff / hi) ** (2 * order))
    h = np.roll(np.fft.irfft(g, taps + 1), (taps + 1) // 2)[: taps] * np.hanning(taps)
    from .sound_design import _convolve

    return _convolve(x.astype(np.float32), h.astype(np.float32))[taps // 2: taps // 2 + len(x)]


def extend_bandwidth(x, sr: int, top_hz: float, bottom_hz: float) -> tuple[Any, list[str]]:
    """Rebuild missing octaves: rectifying the top octave that is there makes its harmonics an octave up (applied
    until ~14 kHz); the band above the low cut makes difference tones at the voice's fundamental for the bottom."""
    np = _np()
    y = x.astype(np.float32).copy()
    did = []
    fc = top_hz
    for _ in range(3):
        if fc >= 0.85 * min(14000.0, sr / 2 - 1000):
            break
        src = _fir_band(np, y, sr, fc * 0.5, fc * 0.97)
        gen = np.abs(src)
        gen = _fir_band(np, gen, sr, fc * 1.02, min(2 * fc, sr / 2 - 500), order=10)
        e_src, e_gen = float(np.mean(src ** 2)), float(np.mean(gen ** 2))
        if e_gen <= 1e-14:
            break
        y += gen * math.sqrt(e_src * 10 ** (-(0.6 if not did else 1.0)) / e_gen)   # -6 then -10 dB per octave, like natural speech
        did.append(f"{fc / 1000:.1f}-{min(2 * fc, sr / 2 - 500) / 1000:.1f} kHz")
        fc = min(2 * fc, sr / 2 - 500)
    if bottom_hz >= 200:
        src = _fir_band(np, y, sr, bottom_hz, bottom_hz * 3)
        gen = _fir_band(np, np.abs(src) - np.abs(src).mean(), sr, 75, bottom_hz * 0.95, order=6)
        e_src, e_gen = float(np.mean(src ** 2)), float(np.mean(gen ** 2))
        if e_gen > 1e-14:
            y += gen * math.sqrt(e_src * 10 ** (-0.6) / e_gen)
            did.append(f"75-{bottom_hz:.0f} Hz")
    return y, did


def dereverb(x, sr: int, strength: float = 0.6, t60: float = 0.5):
    """Late-reverb suppression (a statistical room model, Lebart/Habets style): the reverberant tail at each moment is
    predicted from the signal 50 ms earlier, decayed by the room's T60, and subtracted spectrally (gain floor -18 dB)."""
    np = _np()
    if strength <= 0:
        return x
    nfft, hop = 1024, 256
    pad = nfft
    xp = np.concatenate([np.zeros(pad, np.float32), x.astype(np.float32), np.zeros(pad + nfft, np.float32)])
    win = np.hanning(nfft + 1)[:-1]
    nfr = 1 + (len(xp) - nfft) // hop
    X = np.empty((nfr, nfft // 2 + 1), np.complex64)
    for b0 in range(0, nfr, 2048):
        ii = np.arange(b0, min(nfr, b0 + 2048))
        X[ii] = np.fft.rfft(xp[ii[:, None] * hop + np.arange(nfft)[None, :]] * win, axis=1)
    P = np.abs(X) ** 2
    # smooth power over ~30 ms so the estimate follows the room, not single frames
    Ps = P.copy()
    a = math.exp(-hop / sr / 0.03)
    for i in range(1, nfr):
        Ps[i] = a * Ps[i - 1] + (1 - a) * P[i]
    d = max(1, int(round(0.05 * sr / hop)))
    decay = math.exp(-6.9 * 2 * d * hop / sr / t60) if t60 > 0 else 0.0
    late = np.zeros_like(P)
    late[d:] = decay * Ps[:-d]
    g = 1 - strength * 1.5 * late / (P + 1e-12)
    g = np.maximum(g, 10 ** (-18 / 20))
    for i in range(1, nfr):   # smooth gains in time against "musical noise"
        g[i] = 0.6 * g[i] + 0.4 * g[i - 1]
    Y = X * g.astype(np.float32)
    y = np.zeros(len(xp))
    for b0 in range(0, nfr, 2048):
        ii = np.arange(b0, min(nfr, b0 + 2048))
        fr = np.fft.irfft(Y[ii], nfft, axis=1) * win
        for j, i in enumerate(ii):
            y[i * hop: i * hop + nfft] += fr[j]
    return (y[pad: pad + len(x)] / 1.5).astype(np.float32)


def _noise_floor(np, x, sr: int) -> float:
    w = int(sr * 0.05)
    k = len(x) // w
    if not k:
        return -120.0
    db = 10 * np.log10(np.mean(x[: k * w].astype(np.float64).reshape(k, w) ** 2, axis=1) + 1e-20)
    return round(max(-120.0, float(np.percentile(db, 10))), 1)


