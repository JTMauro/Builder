def _df_shim() -> None:
    """DeepFilterNet's io module imports torchaudio only for file loading and resampling, which Builder does with
    ffmpeg. When torchaudio isn't installed (it has no build for every torch), a tiny stand-in lets df import."""
    import importlib.util
    import sys
    import types

    if importlib.util.find_spec("torchaudio") is not None or "torchaudio" in sys.modules:
        return
    ta = types.ModuleType("torchaudio")
    backend, common, fn = (types.ModuleType(n) for n in ("torchaudio.backend", "torchaudio.backend.common", "torchaudio.functional"))

    class AudioMetaData:  # noqa: D401 - placeholder type
        pass

    def _no(*_a, **_k):
        raise RuntimeError("torchaudio is not installed; Builder resamples with ffmpeg")

    common.AudioMetaData = AudioMetaData
    fn.resample = _no
    ta.backend, backend.common, ta.functional = backend, common, fn
    ta.load = ta.save = ta.info = _no
    sys.modules.update({"torchaudio": ta, "torchaudio.backend": backend, "torchaudio.backend.common": common, "torchaudio.functional": fn})


