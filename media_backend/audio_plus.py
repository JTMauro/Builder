def _bell(fx: _Fx, f: float, dur: float, bright: float = 1.0):
    k = fx.n(dur)
    return fx.modes(k, [(f, dur / 3.5, 1.0), (f * 2.0, dur / 6, 0.25 * bright), (f * 3.0, dur / 9, 0.1 * bright), (f * 4.2, dur / 14, 0.05 * bright)])


def sfx_ui(fx: _Fx, variant: str, length: float):
    np, rng = fx.np, fx.rng
    L, R = fx.zeros(length)
    if variant == "click":
        k = fx.n(0.04)
        s = fx.noise(k, 800, 5000, taps=256) * fx.decay(k, 0.0015, 0.0001) + 0.6 * fx.modes(k, [(2200 * rng.uniform(0.95, 1.05), 0.004, 0.7), (900, 0.004, 0.6)])
        fx.put_st(L, R, 0.005, fx.norm(s), 0.9)
        return L, R
    if variant == "pop":
        k = fx.n(0.12)
        t = fx.t(k)
        f = 420 + 900 * (1 - np.exp(-t / 0.018))
        s = np.sin(2 * math.pi * np.cumsum(f) / fx.SR) * np.clip(t / 0.002, 0, 1) * np.exp(-t / 0.035)
        s = s + 0.25 * fx.noise(k, 1000, 6000, taps=256) * fx.decay(k, 0.002)
        fx.put_st(L, R, 0.005, fx.norm(s.astype(np.float32)), 0.9)
        return L, R
    if variant == "whoosh":
        d = min(length - 0.02, 0.55)
        k = fx.n(d)
        t = fx.t(k) / d
        fc = 260 * (5 ** np.sin(np.pi * np.clip(t * 1.05, 0, 1)))
        s = fx.tv_band(fx.rng.standard_normal(k).astype(np.float32), fc, 1.6) * np.sin(np.pi * t) ** 2
        pan = np.linspace(-0.6, 0.6, k)
        ang = (pan + 1) * math.pi / 4
        s = fx.norm(s)
        L[:k] += s * np.cos(ang)
        R[:k] += s * np.sin(ang)
        return L, R
    if variant == "success":
        for i, (f, at) in enumerate(((784.0, 0.0), (988.0, 0.09), (1175.0, 0.18), (1568.0, 0.27))):
            fx.put_st(L, R, 0.01 + at, _bell(fx, f, 0.9 if i == 3 else 0.5, 0.7), 0.5 if i < 3 else 0.6, -0.2 + 0.13 * i)
        return fx.reverb(L, R, 1.0, 0.18, 7000, 0.015)
    if variant == "error":
        for f, at in ((311.0, 0.0), (233.0, 0.16)):
            k = fx.n(0.15)
            t = fx.t(k)
            tone = fx.band(fx.saw(np.full(k, f)) + 0.5 * fx.saw(np.full(k, f * 1.005)), 100, 2200, taps=512)
            env = np.clip(t / 0.005, 0, 1) * np.clip((0.14 - t) / 0.03, 0, 1)
            fx.put_st(L, R, 0.01 + at, (tone * env).astype(np.float32), 0.6)
        return fx.reverb(L, R, 0.5, 0.1, 5000, 0.01)
    # notification: two-note "ding-dong" (major sixth up)
    fx.put_st(L, R, 0.01, _bell(fx, 880.0, 1.0, 0.8), 0.55, -0.1)
    fx.put_st(L, R, 0.17, _bell(fx, 1318.5, 1.3, 0.8), 0.6, 0.1)
    return fx.reverb(L, R, 1.2, 0.2, 7000, 0.015)


