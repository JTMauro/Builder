@operation("enhance_voice", EnhanceVoiceParams, "Make a rough voice recording sound studio-quality: AI noise and room removal (DeepFilterNet), rebuilds the missing highs and lows of phone/low-quality audio, then EQ, de-essing, gentle compression and loudness. Reports before/after noise floor, bandwidth and loudness. A video keeps its picture.")
def enhance_voice(p: EnhanceVoiceParams) -> OpResult:
    np = _np()
    from .sound_design import _loudness

    src = _src(p.file_id)
    info = media_info(p.file_id)
    if not info["has_audio"]:
        raise OpError("enhance_voice needs a file with sound")
    sr = 48000
    x = _pcm(src, sr)[:, 0].copy()
    if not len(x) or float(np.max(np.abs(x))) < 1e-5:
        raise OpError("enhance_voice found only silence")
    before = {"noise_floor_dbfs": _noise_floor(np, x, sr), **measure_band(x, sr)}
    steps: list[str] = []
    chain: list[str] = ["highpass=f=70"]
    if p.denoise > 0:
        try:
            x = deepfilter(x, p.denoise)
            steps.append(f"DeepFilterNet 3 noise/room removal ({p.denoise:g})")
        except OpError:
            nr = int(6 + 18 * p.denoise)
            chain.insert(0, f"afftdn=nr={nr}:nf=-40:tn=1")
            steps.append(f"ffmpeg afftdn noise removal (DeepFilterNet not installed: pip install deepfilternet torch)")
    if p.dereverb > 0:
        x = dereverb(x, sr, p.dereverb)
        steps.append(f"room echo reduction ({p.dereverb:g})")
    band = measure_band(x, sr)
    if p.bandwidth == "on" or (p.bandwidth == "auto" and (band["top_hz"] < 7000 or band["bottom_hz"] >= 200)):
        x, did = extend_bandwidth(x, sr, min(band["top_hz"], 12000), band["bottom_hz"] if p.bandwidth == "auto" or band["bottom_hz"] >= 200 else 80)
        if did:
            steps.append("bandwidth extension (" + ", ".join(did) + ")")
    eq = list(ENHANCE_EQ[p.style])
    if band["top_hz"] < 7000 and not any("bandwidth" in s for s in steps):
        eq = [e for e in eq if not e.startswith("highshelf")]
    chain += eq
    if p.de_ess:
        chain.append("deesser=i=0.35:m=0.5:f=0.5")
    chain += ["acompressor=threshold=-22dB:ratio=2.5:attack=8:release=160:knee=4", "acompressor=threshold=-10dB:ratio=6:attack=2:release=60"]
    steps.append(f"{p.style} EQ" + (", de-ess" if p.de_ess else "") + ", compression, loudness")
    work = Path(tempfile.mkdtemp(prefix="enh-"))
    try:
        stage = work / "stage.wav"
        _write_wav(stage, x * (0.5 / max(1e-6, float(np.max(np.abs(x))))), sr)
        pre = work / "pre.wav"
        _ffmpeg("-i", str(stage), "-af", ",".join(chain), "-c:a", "pcm_f32le", str(pre))
        m = _loudness(["-i", str(pre)])
        gain = p.loudness - (m["lufs"] if m["lufs"] is not None else p.loudness)
        final = [f"volume={gain:.2f}dB", "alimiter=limit=0.84:attack=3:release=50:level=0"]   # about -1.5 dBFS
        done = work / "done.wav"
        _ffmpeg("-i", str(pre), "-af", ",".join(final), "-c:a", "pcm_s16le", str(done))
        y = _pcm(done, sr)[:, 0]
        after = {"noise_floor_dbfs": _noise_floor(np, y, sr), **measure_band(y, sr), **_loudness(["-i", str(done)])}
        data = {"steps": steps, "before": before, "after": after,
                "check": "Run describe_audio on both files to compare (noise floor, air share, harshness)."}
        if info["has_video"]:
            return _guarded("enhance_voice", [p.file_id], f"{_stem(p.file_id)}_enhanced.mp4",
                            lambda out: _ffmpeg("-i", str(src), "-i", str(done), "-map", "0:v", "-map", "1:a", "-c:v", "copy",
                                                "-c:a", "aac", "-b:a", "192k", "-shortest", str(out)), data=data)
        return _guarded("enhance_voice", [p.file_id], f"{_stem(p.file_id)}_enhanced.{p.format}",
                        lambda out: _ffmpeg("-i", str(done), *AUDIO_CODECS[p.format], str(out)), data=data)
    finally:
        shutil.rmtree(work, ignore_errors=True)


