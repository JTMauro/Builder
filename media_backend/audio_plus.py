def _brass(fx: _Fx, f: float, dur: float, bright: float = 1.0, scoop: float = 0.35, vib: float = 0.12, attack: float = 0.03):
    """Additive brass note: higher harmonics grow faster with loudness (the brass 'blat')."""
    np, rng = fx.np, fx.rng
    k = fx.n(dur + 0.12)
    t = fx.t(k)
    env = np.clip(t / attack, 0, 1) ** 1.5
    env = env * (1 + 0.25 * np.exp(-np.maximum(t - attack, 0) / 0.05) * (t > attack)) / 1.25
    env = env * np.where(t > dur, np.exp(-(t - dur) / 0.04), 1.0)
    vdepth = vib * np.clip((t - 0.25) / 0.2, 0, 1)
    semis = -scoop * np.exp(-t / 0.035) + vdepth * np.sin(2 * math.pi * 5.3 * t)
    ph = np.cumsum(f * 2 ** (semis / 12)) / fx.SR
    out = np.zeros(k)
    for h in range(1, 40):
        if f * h > 12000:
            break
        amp = (1 / h ** 0.8) * (1 + 1.2 * np.exp(-((f * h - 1300) / 900) ** 2))   # the bell's formant
        out += amp * env ** (1 + 0.28 * h / bright) * np.sin(2 * math.pi * h * ph + rng.uniform(0, 6.28))
    out += 0.02 * rng.standard_normal(k) * np.exp(-t / 0.03)   # breath at the attack
    return fx.norm(out.astype(np.float32))


def _hz(name: str) -> float:
    pc = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}[name[0]] + (1 if "#" in name else -1 if name[1:2] == "b" else 0)
    octave = int(name[-1])
    return 440.0 * 2 ** ((pc + 12 * (octave + 1) - 69) / 12)


FANFARES = {   # original phrases built on plain major arpeggios: (note, seconds, harmony notes)
    "short": [("C5", 0.14, []), ("E5", 0.14, []), ("G5", 0.28, ["E5"]), ("E5", 0.12, []), ("G5", 0.12, []), ("C6", 1.0, ["G5", "E5", "C4"])],
    "long": [("G4", 0.13, []), ("C5", 0.13, []), ("E5", 0.13, []), ("G5", 0.4, ["E5", "C4"]), ("F5", 0.13, []), ("A5", 0.13, []),
             ("C6", 0.4, ["A5", "F5", "F3"]), ("B5", 0.13, []), ("A5", 0.13, []), ("G5", 0.13, ["D5"]), ("C6", 1.3, ["G5", "E5", "C4"])],
    "fail": [("G3", 0.42, []), ("F#3", 0.42, []), ("F3", 0.42, []), ("E3", 1.4, [])],
}


def sfx_fanfare(fx: _Fx, variant: str, length: float):
    np, rng = fx.np, fx.rng
    L, R = fx.zeros(length)
    t = 0.03
    fail = variant == "fail"
    for i, (note, d, harm) in enumerate(FANFARES[variant]):
        last = i == len(FANFARES[variant]) - 1
        f = _hz(note)
        if fail:
            if last:   # a wobbling, sinking final note
                s = _brass(fx, f, d, 0.6, 0.3, 0.45, 0.05)
                tt = fx.t(len(s))
                s = s * np.exp(-tt / 2.5)
                wah = 0.6 + 0.4 * np.sin(2 * math.pi * 5.5 * tt)
            else:
                s = _brass(fx, f, d * 0.92, 0.6, 0.5, 0.0, 0.05)
                tt = fx.t(len(s))
                wah = 0.55 + 0.45 * np.sin(np.pi * np.clip(tt / (d * 0.92), 0, 1))
            fx.put_st(L, R, t, (s * wah).astype(np.float32), 0.9, 0.0)
        else:
            for v, pan, det in ((0, -0.25, 1.0), (1, 0.25, 1.003)):
                fx.put_st(L, R, t + 0.006 * v, _brass(fx, f * det, d * 0.9 if not last else d, 1.0 + 0.2 * fx.k, vib=0.12 if last else 0.0), 0.6, pan)
            for j, hn in enumerate(harm):
                hf = _hz(hn)
                fx.put_st(L, R, t + 0.01, _brass(fx, hf, d, 0.8 if hf < 300 else 1.0, 0.2, 0.08), 0.42 if hf >= 300 else 0.5, [-0.5, 0.5, 0.0][j % 3])
        t += d
        if t > length:
            break
    if not fail:   # a timpani-like hit under the last chord
        kn = fx.n(1.2)
        tt = fx.t(kn)
        timp = np.sin(2 * math.pi * 65.4 * tt * (1 + 0.02 * np.exp(-tt / 0.05))) * np.exp(-tt / 0.5) + 0.4 * fx.noise(kn, 60, 800, taps=256) * fx.decay(kn, 0.02)
        fx.put_st(L, R, t - FANFARES[variant][-1][1], fx.norm(timp.astype(np.float32)), 0.5, 0.0)
    return fx.reverb(L, R, 2.0, 0.28, 6000, 0.02)


def sfx_gong(fx: _Fx, variant: str, length: float):
    np, rng = fx.np, fx.rng
    n = fx.n(length)
    big = variant == "big"
    f0 = 58.0 if big else 190.0
    t = fx.t(n)
    out = []
    count = 90 if big else 45
    ratios = np.sort(np.exp(rng.uniform(0, math.log(85 if big else 30), count)))
    amps = rng.uniform(0.4, 1.0, count) / ratios ** 0.2
    taus = (4.0 if big else 2.2) * ratios ** -0.35 * rng.uniform(0.7, 1.2, count) * min(1.0, length / 6 + 0.3)
    rises = 0.02 + (0.5 if big else 0.2) * np.clip(np.log(ratios) / math.log(30), 0, 1) ** 1.5
    for _ch in range(2):
        s = np.zeros(n)
        for r, a, tau, rise in zip(ratios, amps, taus, rises):
            f = f0 * r
            if f > 9000:
                continue
            glide = 1 - (0.012 if big else 0.005) * np.exp(-t / 0.8)   # pitch settles a little as the bloom fades
            ph = 2 * math.pi * np.cumsum(f * glide) / fx.SR + rng.uniform(0, 6.28)
            s += a * np.sin(ph) * (1 - np.exp(-t / rise)) * np.exp(-t / tau)
        out.append(s.astype(np.float32))
    kn = fx.n(0.4)
    tt = fx.t(kn)
    mallet = np.sin(2 * math.pi * (f0 * 1.1) * tt) * np.exp(-tt / 0.12) + 0.3 * fx.noise(kn, 50, 1500, taps=256) * fx.decay(kn, 0.01)
    L, R = fx.norm(out[0]), fx.norm(out[1])
    m = fx.norm(mallet.astype(np.float32))
    L[:kn] += 0.5 * m
    R[:kn] += 0.5 * m
    L, R = L * np.clip((length - t) / 0.5, 0, 1), R * np.clip((length - t) / 0.5, 0, 1)
    return fx.reverb(L.astype(np.float32), R.astype(np.float32), 3.0, 0.25, 5000, 0.02)


