_w2v_cache: dict[str, Any] = {}


def _w2v():
    """The wav2vec2 CTC model and its character vocabulary (downloaded once, ~380 MB)."""
    if "model" in _w2v_cache:
        return _w2v_cache["model"], _w2v_cache["vocab"]
