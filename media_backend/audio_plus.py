def _year(md: dict[str, Any]) -> int | None:
    for k in ("year", "date"):
        m = re.search(r"\b(1[5-9]\d\d|20\d\d)\b", str(md.get(k) or ""))
        if m:
            return int(m.group(1))
    return None


def _trusted(md: dict[str, Any], lic: str, cols: list[Any]) -> bool:
    """Musopen's own recordings, or items marked public domain whose recording date is old enough to be public domain.
    (Uploaders sometimes mark modern recordings 'CC0'; the date check keeps those out.)"""
    if any(str(c).lower().startswith("musopen") for c in cols):
        return True
    y = _year(md)
    return ("publicdomain" in lic) and y is not None and y <= PD_RECORDING_YEAR


