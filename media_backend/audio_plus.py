def _sword_ring(fx: _Fx, k: int, base: float, long: float = 1.0):
    rng = fx.rng
    ratios = [1.0, 1.58, 2.37, 3.11, 4.26, 5.52]
    parts = [(base * r * rng.uniform(0.97, 1.03), long * rng.uniform(0.6, 1.0) * (0.75 / (1 + 0.45 * i)), 1.0 / (1 + 0.6 * i))
             for i, r in enumerate(ratios)]
    return fx.modes(k, parts, detune=4.0)


def sfx_impact(fx: _Fx, variant: str, length: float):
    np, rng = fx.np, fx.rng
    L, R = fx.zeros(length)
    k = fx.k
    if variant == "punch":
        kn = fx.n(0.14)
        sw = fx.tv_band(rng.standard_normal(kn).astype(np.float32), np.linspace(500, 1800, kn), 1.0) * np.linspace(0, 1, kn) ** 2
        fx.put_st(L, R, 0.0, fx.norm(sw), 0.25, 0.0)
        kn = fx.n(0.4)
        t = fx.t(kn)
        f = 48 + 70 * np.exp(-t / 0.03)
        thump = np.sin(2 * math.pi * np.cumsum(f) / fx.SR) * np.exp(-t / (0.07 + 0.04 * k))
        slap = fx.noise(kn, 400, 4000, taps=256) * fx.decay(kn, 0.014, 0.0003)
        knock = fx.modes(kn, [(170, 0.04, 1.0), (320, 0.025, 0.5)])
        hit = fx.soft(fx.norm(0.8 * thump + 1.6 * slap + 0.8 * knock) * (1.2 + 0.8 * k), 2.0)
        fx.put_st(L, R, 0.14, hit, 1.0, 0.0)
        return fx.reverb(L, R, 0.5, 0.1, 5000, 0.008)
    if variant == "thud":
        kn = fx.n(0.7)
        t = fx.t(kn)
        f = 42 + 50 * np.exp(-t / 0.04)
        thump = np.sin(2 * math.pi * np.cumsum(f) / fx.SR) * np.exp(-t / 0.13)
        body = fx.noise(kn, 60, 1200, taps=512) * fx.decay(kn, 0.03, 0.001)
        wood = fx.modes(kn, [(180, 0.05, 1.0), (310, 0.035, 0.6), (520, 0.02, 0.3)])
        fx.put_st(L, R, 0.01, fx.soft(fx.norm(thump + 1.0 * body + 0.5 * wood), 1.4), 1.0, 0.0)
        return fx.reverb(L, R, 0.8, 0.15, 3000, 0.01)
    if variant == "clang":
        kn = fx.n(min(length, 2.5))
        base = rng.uniform(380, 520)
        ring = fx.modes(kn, [(base, 1.2, 0.8), (base * 2.32, 0.9, 0.8), (base * 4.25, 0.7, 0.7), (base * 6.63, 0.5, 0.5), (base * 9.38, 0.35, 0.35), (base * 12.6, 0.2, 0.2)], detune=3.0)
        strike = fx.noise(kn, 1200, 10000, taps=256) * fx.decay(kn, 0.005, 0.0002)
        s = fx.norm(ring + 1.2 * strike)
        fx.put_st(L, R, 0.01, s, 0.9, -0.1)
        fx.put_st(L, R, 0.013, s, 0.3, 0.4)
        return fx.reverb(L, R, 1.2, 0.18, 6000, 0.012)
    if variant == "sword_clash":
        kn = fx.n(min(length, 2.0))
        strike = fx.noise(kn, 2500, 11000, taps=256, tilt=-1.0) * fx.decay(kn, 0.0025, 0.0001)
        a = _sword_ring(fx, kn, rng.uniform(1050, 1350), 0.45 + 0.3 * k)
        b = _sword_ring(fx, kn, rng.uniform(1400, 1800), 0.35 + 0.25 * k)
        scrape_n = fx.n(0.18)
        su = fx.t(scrape_n) / 0.18
        scrape = fx.tv_band(rng.standard_normal(scrape_n).astype(np.float32), 5200 - 2400 * su, 0.6) * np.exp(-su * 3) * (0.6 + 0.4 * rng.random(scrape_n))
        dry = fx.norm(0.9 * strike + 0.55 * a + 0.45 * b)
        dry = fx.band(dry, 250, 9000, taps=512)
        fx.put_st(L, R, 0.01, fx.norm(dry), 0.95, -0.15)
        fx.put_st(L, R, 0.012, fx.norm(b), 0.25, 0.4)
        fx.put_st(L, R, 0.02, fx.norm(scrape.astype(np.float32)), 0.3 + 0.15 * k, 0.1)
        return fx.reverb(L, R, 1.6, 0.2, 6500, 0.015)
    # shield_hit: wooden round shield with a metal boss
    kn = fx.n(1.2)
    wood = fx.fit(_wood_thud(fx, 0.8, 1.5), kn)
    boss = fx.modes(kn, [(rng.uniform(780, 900), 0.22, 1.0), (rng.uniform(1350, 1500), 0.15, 0.6), (rng.uniform(2150, 2400), 0.09, 0.35)], detune=3.0)
    crack = fx.noise(kn, 400, 7000, taps=256) * fx.decay(kn, 0.006, 0.0002)
    low = fx.modes(kn, [(75, 0.09, 1.0)])
    s = fx.soft(fx.norm(1.0 * wood + 0.35 * boss + 0.6 * crack + 0.5 * low) * (1.1 + 0.6 * k), 1.6)
    fx.put_st(L, R, 0.01, s, 1.0, 0.0)
    for _ in range(int(2 + 3 * k)):   # the strap and rim rattle
        fx.put_st(L, R, 0.03 + rng.uniform(0, 0.08), _metal_click(fx, 0.5), rng.uniform(0.04, 0.1), rng.uniform(-0.3, 0.3))
    return fx.reverb(L, R, 1.1, 0.16, 5000, 0.012)


def sfx_swoosh(fx: _Fx, variant: str, length: float):
    np, rng = fx.np, fx.rng
    L, R = fx.zeros(length)
    d = {"light": 0.35, "heavy": 0.6, "sword": 0.3}[variant]
    d = min(d * (1.25 - 0.4 * fx.k), length - 0.02)
    kn = fx.n(d)
    u = fx.t(kn) / d
    shape = np.sin(np.pi * np.clip(u * 1.1, 0, 1)) ** 2 * np.exp(-u * 0.8)
    if variant == "light":
        fc, bw = 450 * 3 ** np.sin(np.pi * u), 1.6
    elif variant == "heavy":
        fc, bw = 220 * 4 ** np.sin(np.pi * u), 1.5
    else:
        fc, bw = 700 * 2.2 ** np.sin(np.pi * u), 0.6
    s = fx.tv_band(rng.standard_normal(kn).astype(np.float32), fc, bw) * shape
    if variant == "sword":
        tone = np.sin(2 * math.pi * np.cumsum(fc * 0.98) / fx.SR) * shape * 0.25
        air = fx.tv_band(rng.standard_normal(kn).astype(np.float32), fc * 2.5, 1.5) * shape
        s = s / (np.max(np.abs(s)) or 1) + tone + 0.35 * air / (np.max(np.abs(air)) or 1)
    if variant == "heavy":
        s = s + 0.5 * fx.norm(fx.noise(kn, 40, 220, taps=1024) * shape)
    s = fx.norm(s.astype(np.float32))
    pan = np.linspace(-0.7, 0.7, kn) * (1 if rng.random() < 0.5 else -1)
    ang = (pan + 1) * math.pi / 4
    L[:kn] += s * np.cos(ang)
    R[:kn] += s * np.sin(ang)
    return L, R


